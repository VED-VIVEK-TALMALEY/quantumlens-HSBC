-- Supabase/PostgreSQL schema for QuantumLens metrics.
-- Review in Supabase SQL Editor before applying; this is not run by the Python loader.
create table if not exists public.metrics (
    id bigint generated by default as identity primary key,
    metric_id integer not null,
    metric_name text not null,
    abbreviation text not null default '',
    period_values jsonb not null default '[]'::jsonb,
    source_workbook text,
    sheet_name text not null,
    row_number integer not null,
    created_at timestamptz not null default now()
);

alter table public.metrics add column if not exists period_values jsonb not null default '[]'::jsonb;
alter table public.metrics add column if not exists source_workbook text;
alter table public.metrics add column if not exists sheet_name text;
alter table public.metrics add column if not exists row_number integer;
alter table public.metrics add column if not exists abbreviation text default '';

create unique index if not exists unique_metric_record
    on public.metrics (metric_id, sheet_name, row_number);
create index if not exists metrics_metric_id_idx on public.metrics (metric_id);
create index if not exists metrics_metric_name_idx on public.metrics (metric_name);
create index if not exists metrics_abbreviation_idx on public.metrics (abbreviation);
